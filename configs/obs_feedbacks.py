# Function to be run that computes observations and climate sensitivities

import pandas as pd
import typing
import logging
import genericLib
from StudyConfig import type_basic
from Model import Model

my_logger = logging.getLogger('UKESM')
#my_logger = genericLib.setup_logging(level='DEBUG',rootname='UKESM')

def comp_obs_feedback(get_model: typing.Callable[[dict[str,type_basic]],typing.Optional[Model]],
                      parameter_dict:dict[str,dict[str,type_basic]],
                      use_cache:bool = True) -> tuple[list[typing.Optional[Model]],typing.Optional[pd.Series]]:

    """
    Function to compute obs and feedbacks for a given run/submit instance and parameter dictionary.
    This function  computes simulated  observations and Cess feeback.
      Assumes using names generated by comp_sim_obs_UKESM1_1_1 and needs two models:
       'control' and 'plus4K' -- AMIP run & AMIP run with +4K SST
       and two obs:
        'netflux_global' and 'T_global'. global mean net TOA flux and global mean surface temperature.
    :param get_model: fn to compute/read simulated observations.
      Should take a dict of parameters and return a Model or None.
    :param parameter_dict: Dict of parameters for models. Should have the keys control and plus4k
    :param use_cache: Passed to compute_simulated_observations
    :return: List of models/None  (or list of None) & Pandas series (or None) observations, of Cess sensitivity & plus4K "obs" (with plus4K- appended to names). 
    """

    models = dict()
    obs = dict()
    # get models and simulated obs. This case has no dependencies between models so is straightforward.
    # a more complex case would be where one model depends on another.
    # in that case would need to run models in expected order checking that they exist before running dependent models.
    # more complex cases could be handled by modifying parameters in models based on results from other models.
    for name,param_dict in parameter_dict.items():
        param_dict.update(reference_name=name)
        model = get_model(param_dict) # this will create a new model or return an existing one.
        if not isinstance(model,(Model,type(None))):
            raise ValueError(f"get_model returned {type(model)} instead of a Model")
        my_logger.debug(f" config name: {name} model name {model.name} reference: {model.reference}")
        models[name]=model
        if model is None:
            obs[name]= None
        else:
            obs[name]=model.compute_simulated_observations(use_cache=use_cache)
            
    # test that all models ran and produced obs. Any that are None will mean can't compute result.
    if any([o is None for o in obs.values()]):
        return list(models.values()),None
    # now we can compute the feedbacks
    d_flux = obs['plus4K'].loc['netflux_global'] - obs['control'].loc['netflux_global']
    d_temp =  obs['plus4K'].loc['T2m_global'] - obs['control'].loc['T2m_global'] # should be close to 4K. Slightly different as land may warm more than ocean.
    cess = -d_flux/d_temp # Cess feedback in W/m2/K
    my_logger.debug(f'Computed CESS = {cess} W/m2/K for dFlux={d_flux} W/m2 and dtemp={d_temp} K')
    result = pd.concat([obs['control'],pd.Series({'Cess':cess})])
    # and then add on the plus4K data so have that.
    rename = {k:f'plus4K-{k}' for k in obs['plus4K'].index}
    plus4k = obs['plus4K'].rename(index=rename)
    result = pd.concat([result,plus4k])
    return list(models.values()),result

